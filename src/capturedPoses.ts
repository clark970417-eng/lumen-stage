/**
 * Poses captured from recorded performance, not solved from joint angles.
 *
 * Each entry is one frame of a Microsoft Rocketbox motion clip (MIT licence),
 * sampled offline by scripts/capture-build.html and stored as a rotation delta
 * from the rest pose of the rig it was read off. Deltas rather than absolute
 * rotations because the two actors do not share a rest: their bones sit up to
 * 14 degrees apart, so replaying absolute rotations bent one of them wrong.
 *
 * Contacts record where a hand was resting, in the local frame of the bone it
 * rested on. The actors are not the same proportions — one has arms 13% longer
 * on legs 6% shorter — so the same joint angles put a hand several centimetres
 * off the chin it was touching. The contact is what the IK puts back.
 *
 * Generated. Re-run scripts/capture-build.html to change it.
 */


export type CapturedContact = {
  hand: 'left' | 'right'
  /** Bone the hand rests on, by its name in the source rig. */
  anchor: string
  /** Where the hand sat, in that bone's local frame, in the source rig's units. */
  offset: [number, number, number]
}

export type CapturedPose = {
  id: string
  /** Clip and timecode this frame came from. */
  source: string
  /** Head above foot in the source rig, so contacts can be scaled to an actor. */
  stature: number
  /** Rotation delta from rest, by bone name. Bones left at rest are absent. */
  rotation: Record<string, [number, number, number, number]>
  contacts: CapturedContact[]
}

