/**
 * Translates a catalogue entry by id, falling back to the catalogue's own text.
 */
export function translateCatalog(locale: Locale, id: string, fallback: string) {
  if (locale === 'en') return fallback
  return CATALOG[id]?.[locale] ?? fallback
}

export function useCatalogT() {
  const locale = useLocaleStore((state) => state.locale)
  return (id: string, fallback: string) => translateCatalog(locale, id, fallback)
}
